function getI18n(langCode) {
  if (!langCode || langCode === 'auto') {
    const envLang = (process.env.VSCODE_NLS_CONFIG ? JSON.parse(process.env.VSCODE_NLS_CONFIG).locale : process.env.LANG || 'en').slice(0, 2).toLowerCase();
    if (translations[envLang]) return translations[envLang];
    return translations.en;
  }
  return translations[langCode] || translations.en;
}

